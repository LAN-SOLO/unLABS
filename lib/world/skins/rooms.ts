/**
 * One skin concept per room (docs/SKINS.md § Rooms). Every concept is
 * complete enough to build: wall family + parameters, bands and glyphs,
 * floor family, a signature mood, recommended presets and the events that
 * take the skin over. `voxels.ts` turns it into fine voxels; the Blender
 * renders (pnpm skins:render) are made from exactly this data.
 *
 * Wall face coordinates (fine voxels, 4 per source voxel): v 0 … 3 base,
 * v 4 … 27 panel zone (24 high), v 28 … 31 cap. Bands use v in the panel zone.
 */
import { tr } from "@/lib/i18n";
import type {
  FloorSpec,
  RoomSkin,
  SkinMode,
  SkinPreset,
  SkinSource,
  WallSpec,
} from "@/lib/world/skins/types";

type WallIn = Partial<Omit<WallSpec, "paint">> & { paint?: Partial<WallSpec["paint"]> };
type FloorIn = Partial<Omit<FloorSpec, "paint">> & { paint?: Partial<FloorSpec["paint"]> };

