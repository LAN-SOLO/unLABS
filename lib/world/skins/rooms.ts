const FLOOR0: FloorSpec = {
  family: "tiles",
  tile: 16,
  paint: {
    a: "floor_tile",
    b: "floor_dark",
    grout: "floor_dark",
    border: "metal_dark",
    line: "line",
    node: "node",
  },
  lines: "none",
  diamonds: false,
  cracks: false,
};

function wall(family: WallSpec["family"], o: WallIn = {}): WallSpec {
  return { ...WALL0, ...o, family, paint: { ...WALL0.paint, ...o.paint } };
}

function floor(family: FloorSpec["family"], o: FloorIn = {}): FloorSpec {
  return { ...FLOOR0, ...o, family, paint: { ...FLOOR0.paint, ...o.paint } };
}

function sig(
  room: string,
  name: string,
  line: string,
  node: string,
  field: string,
  fieldGlow: number,
  mode: SkinMode,
  speed = 1,
  intensity = 1,
  source?: SkinSource,
  line2?: string,
): SkinPreset {
  return {
    id: `sig_${room}`,
    name,
    line,
    line2,
    node,
    field,
    fieldGlow,
    mode,
    speed,
    intensity,
    source,
  };
}

